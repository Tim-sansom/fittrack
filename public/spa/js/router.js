    /**
     * renderWorkoutsInfiniteScroll
     * Implements a Facebook-style infinite scroll feed. It renders an initial 
     * batch of workout cards and uses the IntersectionObserver API to detect 
     * when the user scrolls near the bottom, appending the next batch of DOM nodes.
     */
    function renderWorkoutsInfiniteScroll(data, container) {
        if (!Array.isArray(data) || data.length === 0) {
            container.innerHTML = '<div style="padding: 2rem; text-align: center;">No workout data found.</div>';
            return;
        }

        container.innerHTML = `
            <div style="max-width: 800px; margin: 0 auto;">
                <h3 style="margin-bottom: 1rem; color: var(--text);">Recent Workouts</h3>
                <div id="workout-feed"></div>
                <div id="scroll-sentinel" style="height: 40px; text-align: center; padding: 1rem; color: var(--text); opacity: 0.6;">Loading more...</div>
            </div>
        `;

        const feed = document.getElementById('workout-feed');
        const sentinel = document.getElementById('scroll-sentinel');
        let currentIndex = 0;
        const batchSize = 5;

        function createWorkoutCard(item) {
            const div = document.createElement('div');
            div.className = 'activity-card';
            div.style.cssText = 'background: var(--card); padding: 1.5rem; border-radius: 12px; box-shadow: 0 2px 8px var(--shadow); display: flex; justify-content: space-between; align-items: center; margin-bottom: 1rem; opacity: 0; transform: translateY(20px); transition: all 0.4s ease;';
            
            const title = item.title || 'Workout';
            const duration = item.duration_minutes || 0;
            const date = item.activity_date ? new Date(item.activity_date).toLocaleDateString('en-GB') : 'Unknown';
            
            div.innerHTML = `
                <div>
                    <h4 style="margin: 0 0 0.5rem 0; color: var(--accent);">${title}</h4>
                    <span style="font-size: 0.9rem; opacity: 0.8;">${date}</span>
                </div>
                <div style="text-align: right;">
                    <div style="font-size: 1.2rem; font-weight: bold;">${duration} mins</div>
                </div>
            `;
            
            requestAnimationFrame(() => {
                div.style.opacity = '1';
                div.style.transform = 'translateY(0)';
            });
            return div;
        }

        function loadNextBatch() {
            if (currentIndex >= data.length) {
                sentinel.textContent = 'End of feed';
                observer.disconnect();
                return;
            }
            const nextBatch = data.slice(currentIndex, currentIndex + batchSize);
            nextBatch.forEach(item => feed.appendChild(createWorkoutCard(item)));
            currentIndex += batchSize;
        }

        loadNextBatch();

        const observer = new IntersectionObserver((entries) => {
            if (entries[0].isIntersecting) {
                setTimeout(loadNextBatch, 500);
            }
        }, { 
            root: scrollContainer, 
            threshold: 0.1 
        });

        observer.observe(sentinel);
    }

